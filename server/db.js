import pg from 'pg';
import dotenv from 'dotenv';
import './runtime-config.js';
import { readFileSync } from 'node:fs';
dotenv.config();

const { Pool } = pg;

export const isPostgres = Boolean(process.env.DATABASE_URL);

export const pool = isPostgres
  ? new Pool({
      connectionString: process.env.DATABASE_URL,
      ssl: process.env.PGSSLMODE === 'disable' ? false : process.env.NODE_ENV === 'production' ? {rejectUnauthorized:true} : false,
      max: Number(process.env.PG_POOL_SIZE || 20),
      idleTimeoutMillis: 30000,
      connectionTimeoutMillis: 5000
    })
  : null;

if (pool) {
  pool.on('error', (err) => {
    console.error('Unexpected error on idle PostgreSQL client:', err);
  });
}

// In-memory fallback stores for offline local development without Railway PostgreSQL
const memStore = {
  profiles: new Map(),
  tasteProfiles: new Map(),
  savedRestaurants: new Map(), // key: `${userId}:${restaurantId}`
  interactions: [],
  events: [],
  waitlist: new Map(),
  connections: new Map()
};

/**
 * Execute a SQL query if connected to PostgreSQL, or use in-memory mock store
 */
export async function query(text, params = []) {
  if (pool) {
    return pool.query(text, params);
  }
  return { rows: [], rowCount: 0 };
}

/**
 * Initialize Palateo domain tables in PostgreSQL
 */
export async function initializeSchema() {
  if (!pool) {
    console.log('[Palateo DB] No DATABASE_URL found. Running with in-memory stores for local preview.');
    return;
  }

  console.log('[Palateo DB] Verifying and applying database schema in PostgreSQL...');

  const schemaSql = `
    -- Better Auth tables will be generated by Better Auth CLI or migration script
    -- Palateo Domain Profiles
    CREATE TABLE IF NOT EXISTS public.profiles (
      id TEXT PRIMARY KEY,
      display_name TEXT,
      phone TEXT,
      email TEXT,
      profile_photo_url TEXT,
      bio TEXT,
      onboarding_completed BOOLEAN DEFAULT FALSE,
      created_at TIMESTAMPTZ DEFAULT NOW(),
      updated_at TIMESTAMPTZ DEFAULT NOW()
    );

    -- Palateo Taste Profiles
    CREATE TABLE IF NOT EXISTS public.taste_profiles (
      user_id TEXT PRIMARY KEY,
      cuisines JSONB DEFAULT '{}'::jsonb,
      spice_level TEXT,
      budget TEXT,
      ambience JSONB DEFAULT '{}'::jsonb,
      occasions JSONB DEFAULT '{}'::jsonb,
      priorities JSONB DEFAULT '{}'::jsonb,
      max_distance_km NUMERIC,
      confidence NUMERIC DEFAULT 82,
      taste_vector JSONB DEFAULT '{}'::jsonb,
      updated_at TIMESTAMPTZ DEFAULT NOW()
    );

    -- Saved Restaurants
    CREATE TABLE IF NOT EXISTS public.saved_restaurants (
      id BIGSERIAL PRIMARY KEY,
      user_id TEXT NOT NULL,
      restaurant_id TEXT NOT NULL,
      created_at TIMESTAMPTZ DEFAULT NOW(),
      UNIQUE(user_id, restaurant_id)
    );

    -- User Interactions (likes, passes, visits)
    CREATE TABLE IF NOT EXISTS public.interactions (
      id BIGSERIAL PRIMARY KEY,
      user_id TEXT NOT NULL,
      restaurant_id TEXT NOT NULL,
      type TEXT NOT NULL,
      source TEXT DEFAULT 'palateo_v5',
      metadata JSONB DEFAULT '{}'::jsonb,
      created_at TIMESTAMPTZ DEFAULT NOW()
    );

    -- Connections (Follows / Foodie network)
    CREATE TABLE IF NOT EXISTS public.connections (
      id BIGSERIAL PRIMARY KEY,
      requester_id TEXT NOT NULL,
      recipient_id TEXT NOT NULL,
      status TEXT DEFAULT 'pending',
      created_at TIMESTAMPTZ DEFAULT NOW(),
      UNIQUE(requester_id, recipient_id)
    );

    -- App Telemetry Events
    CREATE TABLE IF NOT EXISTS public.app_events (
      id BIGSERIAL PRIMARY KEY,
      user_id TEXT NOT NULL,
      event_name TEXT NOT NULL,
      metadata JSONB DEFAULT '{}'::jsonb,
      created_at TIMESTAMPTZ DEFAULT NOW()
    );

    -- Launch Waitlist
    CREATE TABLE IF NOT EXISTS public.launch_waitlist (
      id BIGSERIAL PRIMARY KEY,
      email TEXT UNIQUE NOT NULL,
      city TEXT NOT NULL,
      consent BOOLEAN NOT NULL DEFAULT FALSE,
      created_at TIMESTAMPTZ DEFAULT NOW()
    );

    -- Indexes for high-performance lookups
    CREATE INDEX IF NOT EXISTS idx_saved_restaurants_user ON public.saved_restaurants(user_id);
    CREATE INDEX IF NOT EXISTS idx_interactions_user ON public.interactions(user_id, created_at);
    CREATE INDEX IF NOT EXISTS idx_app_events_user ON public.app_events(user_id);
  `;

  try {
    await pool.query(schemaSql);
    await pool.query(readFileSync(new URL('./account-deletion.sql', import.meta.url),'utf8'));
    console.log('[Palateo DB] Schema initialized successfully ✓');
  } catch (error) {
    console.error('[Palateo DB] Schema initialization error:', error.message);
    throw error;
  }
}

export { memStore };
