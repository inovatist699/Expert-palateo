delete state.feedback.train;
assert.deepEqual(ranked(),baseline,'Undo must restore exact scores and order');
state.feedback.train='like';
assert.deepEqual(ranked(),learned,'Restoring feedback must restore exact scores and order');
const legacy=[{id:'low',score:50},{id:'high',score:60}];
assert.equal(legacy.sort(compareRecommendations)[0].id,'high','Legacy score-only callers remain supported');
